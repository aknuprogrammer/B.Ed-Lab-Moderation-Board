// 1. We use a local worker copied with .js extension (/pdf.worker.min.js) so Nginx returns 'application/javascript'.
// 2. We also provide a high-reliability CDN fallback (jsDelivr) if the local file is not reachable.
const LOCAL_WORKER_URL = '/pdf.worker.min.js';
const CDN_WORKER_URL = 'https://cdn.jsdelivr.net/npm/pdfjs-dist@6.2.108/build/pdf.worker.min.mjs';

if (typeof window !== 'undefined') {
  pdfjsLib.GlobalWorkerOptions.workerSrc = LOCAL_WORKER_URL;
}

// Reusable ZXing reader instance
let zxingReader = null;
function getZxingReader() {
  if (!zxingReader && typeof window !== 'undefined') {
    try {
      zxingReader = new BrowserQRCodeReader();
    } catch (err) {
      console.warn('Failed to initialize BrowserQRCodeReader:', err);
    }
  }
  return zxingReader;
}

// Reusable native BarcodeDetector instance (hardware/ML accelerated in Chrome, Edge, Android)
let nativeBarcodeDetector = null;
function getNativeBarcodeDetector() {
  if (!nativeBarcodeDetector && typeof window !== 'undefined' && 'BarcodeDetector' in window) {
    try {
      nativeBarcodeDetector = new window.BarcodeDetector({ formats: ['qr_code'] });
    } catch (err) {
      console.warn('Native BarcodeDetector not supported:', err);
    }
  }
  return nativeBarcodeDetector;
}

/**
 * Normalizes a string by stripping punctuation, hyphens, and whitespace for fuzzy comparison.
 */
function normalize(str) {
  return (str || '').toString().toUpperCase().replace(/[^A-Z0-9]/g, '');
}

/**
 * Parses the QR payload format generated by the portal:
 * Typical format: `${rollNumber}-${subjectCode}-${semester}`
 * Examples:
 *   - '256059202052-P-ED-10-1-1'
 *   - '256059202052-MATHEMATICS-1-1'
 *   - '240011223344-BED201-2'
 *   - '256059202052-P-ED-14-1'
 */
export function parseQrPayload(qrText) {
  const raw = (qrText || '').trim();
  const firstHyphen = raw.indexOf('-');
  if (firstHyphen === -1) {
    return { rollNumber: raw, subjectPart: '', semester: '', raw };
  }

  const rollNumber = raw.substring(0, firstHyphen).trim();
  let remainder = raw.substring(firstHyphen + 1).trim();
  let semester = '';

  // Extract semester from the end (e.g. -1-1, -1-2, -2-1, -2-2, -1, -2, -3, -4)
  const semMatch = remainder.match(/-(1-1|1-2|2-1|2-2|[1-4])$/i);
  if (semMatch) {
    semester = semMatch[1];
    remainder = remainder.substring(0, remainder.length - semMatch[0].length);
  }

  const subjectPart = remainder.trim();
  return { rollNumber, subjectPart, semester, raw };
}

/* ==========================================================================
   IMAGE ENHANCEMENT & PREPROCESSING PIPELINE
   Designed specifically for dark, low-contrast, or 11zon-compressed scans.
   ========================================================================== */

/**
 * Auto-levels (contrast stretch) + Gamma correction (shadow brightening).
 * Lifts dark, underexposed paper scans so dark grey QR modules become black
 * and grey/yellowish paper becomes crisp white.
 */
function createEnhancedImageData(imageData, { gamma = 0.58, contrastBoost = 1.35 } = {}) {
  const data = imageData.data;
  const len = data.length;
  const out = new Uint8ClampedArray(len);

  // Compute approximate min & max luminance across the image
  let minLum = 255;
  let maxLum = 0;

  for (let i = 0; i < len; i += 16) {
    const lum = Math.round(0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2]);
    if (lum < minLum) minLum = lum;
    if (lum > maxLum) maxLum = lum;
  }

  if (maxLum - minLum < 20) {
    minLum = Math.max(0, minLum - 25);
    maxLum = Math.min(255, maxLum + 25);
  }

  const range = (maxLum - minLum) || 1;

  // Build 256-entry lookup table for ultra-fast processing
  const lut = new Uint8Array(256);
  for (let v = 0; v < 256; v++) {
    let norm = (v - minLum) / range;
    if (norm < 0) norm = 0;
    if (norm > 1) norm = 1;

    // Gamma correction: norm^gamma brightens midtones & dark shadows
    let boosted = Math.pow(norm, gamma);

    // Contrast boost centered around 0.5
    if (contrastBoost !== 1.0) {
      boosted = (boosted - 0.5) * contrastBoost + 0.5;
      if (boosted < 0) boosted = 0;
      if (boosted > 1) boosted = 1;
    }

    lut[v] = Math.round(boosted * 255);
  }

  for (let i = 0; i < len; i += 4) {
    const lum = Math.round(0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2]);
    const enhanced = lut[lum];
    out[i] = enhanced;
    out[i + 1] = enhanced;
    out[i + 2] = enhanced;
    out[i + 3] = data[i + 3];
  }

  return new ImageData(out, imageData.width, imageData.height);
}

/**
 * Otsu's optimal thresholding binarization (pure black & white).
 * Perfect when uneven shadows or lighting gradients cause standard decoders to fail.
 */
function createThresholdedImageData(imageData) {
  const data = imageData.data;
  const len = data.length;
  const out = new Uint8ClampedArray(len);
  const totalPixels = len / 4;

  const hist = new Int32Array(256);
  for (let i = 0; i < len; i += 4) {
    const lum = Math.round(0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2]);
    hist[lum]++;
  }

  let sum = 0;
  for (let i = 0; i < 256; i++) sum += i * hist[i];

  let sumB = 0;
  let wB = 0;
  let varMax = 0;
  let threshold = 128;

  for (let t = 0; t < 256; t++) {
    wB += hist[t];
    if (wB === 0) continue;
    const wF = totalPixels - wB;
    if (wF === 0) break;

    sumB += t * hist[t];
    const mB = sumB / wB;
    const mF = (sum - sumB) / wF;

    const varBetween = wB * wF * (mB - mF) * (mB - mF);
    if (varBetween > varMax) {
      varMax = varBetween;
      threshold = t;
    }
  }

  for (let i = 0; i < len; i += 4) {
    const lum = 0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2];
    const val = lum >= threshold ? 255 : 0;
    out[i] = val;
    out[i + 1] = val;
    out[i + 2] = val;
    out[i + 3] = 255;
  }

  return new ImageData(out, imageData.width, imageData.height);
}

/**
 * 3x3 Sharpening filter to restore edge definition on compressed PDFs (e.g. 11zon / CamScanner).
 */
function createSharpenedImageData(imageData) {
  const w = imageData.width;
  const h = imageData.height;
  const src = imageData.data;
  const out = new Uint8ClampedArray(src.length);

  for (let i = 3; i < src.length; i += 4) out[i] = src[i];

  for (let y = 1; y < h - 1; y++) {
    for (let x = 1; x < w - 1; x++) {
      const idx = (y * w + x) * 4;
      for (let c = 0; c < 3; c++) {
        const val = 5 * src[idx + c]
          - src[((y - 1) * w + x) * 4 + c]
          - src[((y + 1) * w + x) * 4 + c]
          - src[(y * w + (x - 1)) * 4 + c]
          - src[(y * w + (x + 1)) * 4 + c];
        out[idx + c] = val < 0 ? 0 : (val > 255 ? 255 : val);
      }
    }
  }

  return new ImageData(out, w, h);
}

/**
 * Converts ImageData to an HTMLCanvasElement so canvas-based engines (ZXing, BarcodeDetector) can read it.
 */
function imageDataToCanvas(imgData) {
  const canvas = document.createElement('canvas');
  canvas.width = imgData.width;
  canvas.height = imgData.height;
  const ctx = canvas.getContext('2d');
  ctx.putImageData(imgData, 0, 0);
  return canvas;
}

/**
 * Scans an ImageData buffer using jsQR with inverted attempts.
 */
function scanImageDataWithJsQR(imageData) {
  if (!imageData || !imageData.data || imageData.width < 10 || imageData.height < 10) {
    return null;
  }
  try {
    const code = jsQR(imageData.data, imageData.width, imageData.height, {
      inversionAttempts: 'attemptBoth'
    });
    if (code && code.data && code.data.trim()) {
      return code.data.trim();
    }
  } catch {
    // Ignore and continue
  }
  return null;
}

/**
 * Scans a canvas element using native BarcodeDetector (Chrome/Edge/Android).
 */
async function scanWithNativeBarcodeDetector(canvas) {
  const detector = getNativeBarcodeDetector();
  if (!detector || !canvas) return null;
  try {
    const barcodes = await detector.detect(canvas);
    if (barcodes && barcodes.length > 0) {
      for (const b of barcodes) {
        if (b.rawValue && b.rawValue.trim()) {
          return b.rawValue.trim();
        }
      }
    }
  } catch {
    // Ignore and fallback
  }
  return null;
}

/**
 * Scans a canvas element using @zxing/library BrowserQRCodeReader.
 */
function scanWithZxing(canvas) {
  const reader = getZxingReader();
  if (!reader || !canvas) return null;
  try {
    const result = reader.decode(canvas);
    if (result) {
      const text = typeof result.getText === 'function' ? result.getText() : (result.text || '');
      if (text && text.trim()) {
        return text.trim();
      }
    }
  } catch {
    // Expected NotFoundException when no QR on this region
  }
  return null;
}

/**
 * Releases canvas backing memory immediately (prevents mobile browser crashes/OOM).
 */
function releaseCanvas(canvas) {
  if (canvas) {
    canvas.width = 0;
    canvas.height = 0;
  }
}

/**
 * Decodes a cropped region or canvas using multi-engine + multi-pass enhancement.
 * Sequence:
 *   1. Native BarcodeDetector on original canvas
 *   2. jsQR on original ImageData
 *   3. ZXing on original canvas
 *   4. Brightness & Contrast Enhanced pass (Gamma boost + Auto-levels) -> jsQR, BarcodeDetector, ZXing
 *   5. Otsu Binarization (Pure B&W) -> jsQR
 *   6. Sharpened + Brightened pass -> jsQR
 */
async function decodeRegionMultiEngine(regionCanvas, regionCtx) {
  if (!regionCanvas || regionCanvas.width < 10 || regionCanvas.height < 10) {
    return null;
  }

  // Pass 1: Native BarcodeDetector (fastest and best low-light recognition)
  let codeText = await scanWithNativeBarcodeDetector(regionCanvas);
  if (codeText) return codeText;

  const rawImg = regionCtx.getImageData(0, 0, regionCanvas.width, regionCanvas.height);

  // Pass 2: jsQR on raw ImageData
  codeText = scanImageDataWithJsQR(rawImg);
  if (codeText) return codeText;

  // Pass 3: ZXing HybridBinarizer on raw canvas
  codeText = scanWithZxing(regionCanvas);
  if (codeText) return codeText;

  // Pass 4: Brightness Boost + Dynamic Contrast Stretching (solves dark & underexposed scans)
  const enhancedImg = createEnhancedImageData(rawImg, { gamma: 0.55, contrastBoost: 1.4 });
  codeText = scanImageDataWithJsQR(enhancedImg);
  if (codeText) return codeText;

  const enhancedCanvas = imageDataToCanvas(enhancedImg);
  try {
    codeText = await scanWithNativeBarcodeDetector(enhancedCanvas);
    if (codeText) return codeText;

    codeText = scanWithZxing(enhancedCanvas);
    if (codeText) return codeText;
  } finally {
    releaseCanvas(enhancedCanvas);
  }

  // Pass 5: Otsu Adaptive Binarization (solves uneven shadows & grey background)
  const binarizedImg = createThresholdedImageData(rawImg);
  codeText = scanImageDataWithJsQR(binarizedImg);
  if (codeText) return codeText;

  // Pass 6: Sharpening (solves 11zon / JPEG compression blur)
  const sharpImg = createSharpenedImageData(rawImg);
  codeText = scanImageDataWithJsQR(sharpImg);
  if (codeText) return codeText;

  const sharpEnhanced = createEnhancedImageData(sharpImg, { gamma: 0.55, contrastBoost: 1.45 });
  codeText = scanImageDataWithJsQR(sharpEnhanced);
  if (codeText) return codeText;

  return null;
}

/**
 * Extracts a region from the main canvas and tests it through the decoding pipeline.
 */
async function testCanvasRegion(canvas, context, x, y, width, height) {
  if (width < 20 || height < 20) return null;
  const subCanvas = document.createElement('canvas');
  subCanvas.width = width;
  subCanvas.height = height;
  try {
    const subCtx = subCanvas.getContext('2d', { willReadFrequently: true });
    subCtx.drawImage(canvas, x, y, width, height, 0, 0, width, height);
    return await decodeRegionMultiEngine(subCanvas, subCtx);
  } finally {
    releaseCanvas(subCanvas);
  }
}

/**
 * Rotates a canvas by the given angle in degrees (90 or 270) for sideways scans.
 */
function rotateCanvas(canvas, degrees = 90) {
  const rot = document.createElement('canvas');
  rot.width = canvas.height;
  rot.height = canvas.width;
  const ctx = rot.getContext('2d', { willReadFrequently: true });
  ctx.translate(rot.width / 2, rot.height / 2);
  ctx.rotate((degrees * Math.PI) / 180);
  ctx.drawImage(canvas, -canvas.width / 2, -canvas.height / 2);
  return rot;
}

/**
 * Extracts and decodes QR codes from a rendered HTML Canvas.
 * Tries multiple region crops and image enhancements:
 * 1. Bottom-right quadrant (exact placement of the QR code in BarcodePDF)
 * 2. Bottom 45% band
 * 3. Full canvas
 * 4. Bottom-left quadrant (for alternate layouts)
 * 5. Top 45% (in case student scanned the page inverted/upside down)
 * 6. 90-degree & 270-degree rotated canvas (in case student scanned sideways)
 */
async function findQrOnCanvas(canvas, context) {
  const width = canvas.width;
  const height = canvas.height;

  // 1. Try bottom-right quadrant (highest likelihood - exact placement in footer)
  const brX = Math.floor(width * 0.40);
  const brY = Math.floor(height * 0.55);
  const brW = width - brX;
  const brH = height - brY;
  let codeText = await testCanvasRegion(canvas, context, brX, brY, brW, brH);
  if (codeText) return codeText;

  // 2. Try bottom 45% band
  const bottomY = Math.floor(height * 0.55);
  const bottomH = height - bottomY;
  codeText = await testCanvasRegion(canvas, context, 0, bottomY, width, bottomH);
  if (codeText) return codeText;

  // 3. Try full canvas
  codeText = await decodeRegionMultiEngine(canvas, context);
  if (codeText) return codeText;

  // 4. Try bottom-left quadrant (for alternate layouts)
  const blW = Math.floor(width * 0.60);
  codeText = await testCanvasRegion(canvas, context, 0, bottomY, blW, bottomH);
  if (codeText) return codeText;

  // 5. Try top 45% (upside down / inverted scan)
  const topH = Math.floor(height * 0.45);
  codeText = await testCanvasRegion(canvas, context, 0, 0, width, topH);
  if (codeText) return codeText;

  // 6. Try 90-degree and 270-degree rotated canvases (sideways/landscape scan)
  for (const angle of [90, 270]) {
    let rotCanvas = null;
    try {
      rotCanvas = rotateCanvas(canvas, angle);
      const rotCtx = rotCanvas.getContext('2d', { willReadFrequently: true });
      codeText = await decodeRegionMultiEngine(rotCanvas, rotCtx);
      if (codeText) return codeText;
    } catch {
      // Rotation fallback failed, continue
    } finally {
      releaseCanvas(rotCanvas);
    }
  }

  return null;
}

/**
 * Renders a PDF page to a memory-bounded canvas.
 * Caps the longest edge so mobile scanner PDFs with oversized page points don't OOM.
 */
async function renderPageToCanvas(page, scaleOrOpts = { targetMaxDim: 1850, minScale: 0.6, maxScale: 2.5 }) {
  let scale;
  if (typeof scaleOrOpts === 'number') {
    scale = scaleOrOpts;
  } else {
    const { targetMaxDim = 1850, minScale = 0.6, maxScale = 2.5 } = scaleOrOpts || {};
    const baseViewport = page.getViewport({ scale: 1 });
    const maxSide = Math.max(baseViewport.width, baseViewport.height) || 842;
    scale = Math.max(minScale, Math.min(maxScale, targetMaxDim / maxSide));
  }
  const viewport = page.getViewport({ scale });
  const canvas = document.createElement('canvas');
  canvas.width = Math.max(1, Math.floor(viewport.width));
  canvas.height = Math.max(1, Math.floor(viewport.height));
  const context = canvas.getContext('2d', { willReadFrequently: true });
  await page.render({ canvasContext: context, viewport }).promise;
  return { canvas, context };
}

/**
 * Normalizes OCR digit lookalikes (O->0, I/L->1, S->5, B->8, Z->2) for numeric roll checks.
 */
function normalizeNumericLookalikes(str) {
  return (str || '')
    .toString()
    .toUpperCase()
    .replace(/O|Q|D/g, '0')
    .replace(/I|L|\|/g, '1')
    .replace(/Z/g, '2')
    .replace(/S/g, '5')
    .replace(/B/g, '8')
    .replace(/[^0-9]/g, '');
}

/**
 * Validates extracted text (from PDF text layer or Tesseract OCR) from Certificate Page 1
 * against the student's Roll Number and target Subject.
 */
export function validateCertificateText(
  rawText,
  { expectedRoll = '', expectedSubCode = '', expectedGroupName = '', expectedSubName = '' } = {}
) {
  const text = (rawText || '').toString();
  const normText = normalize(text);
  if (normText.length < 20) {
    return { valid: false, definitiveMismatch: false };
  }

  const normExpectedRoll = normalize(expectedRoll);
  const normExpectedSubCode = normalize(expectedSubCode);
  const normExpectedGroup = normalize(expectedGroupName);
  const normExpectedSubName = normalize(expectedSubName);

  // 1. Ensure page text looks like a Certificate cover page
  const certStems = [
    'CERTIF',
    'NANNAYA',
    'REGISTRAT',
    'UNDERTAK',
    'ACCOMPLISH',
    'HANDWRIT',
    'PRINCIPAL',
    'SEMESTER',
    'RECORDOF'
  ];
  if (!certStems.some((stem) => normText.includes(stem))) {
    return { valid: false, definitiveMismatch: false };
  }

  // 2. Roll Number Check
  let rollMatches = false;
  if (!normExpectedRoll) {
    rollMatches = true;
  } else if (normText.includes(normExpectedRoll)) {
    rollMatches = true;
  } else if (/^\d{6,}$/.test(normExpectedRoll)) {
    const tokens = text.toUpperCase().match(/[A-Z0-9|]{6,}/g) || [];
    for (const tok of tokens) {
      const digitCount = (tok.match(/\d/g) || []).length;
      if (digitCount / tok.length >= 0.7) {
        const normDigits = normalizeNumericLookalikes(tok);
        if (normDigits.includes(normExpectedRoll)) {
          rollMatches = true;
          break;
        }
      }
    }
  }

  if (!rollMatches) {
    const minLen = Math.max(8, normExpectedRoll.length - 1);
    const regMatch = text.match(/Registration\s*(?:No|Number)?\s*[:-]?\s*([A-Z0-9]{6,20})/i);
    const candidateRolls = text.match(new RegExp(`\\b\\d{${minLen},16}\\b`, 'g')) || [];
    const detectedOther = regMatch?.[1] || candidateRolls[0];
    if (detectedOther && normalize(detectedOther) !== normExpectedRoll) {
      return {
        valid: false,
        definitiveMismatch: true,
        error: `Student Roll Number Mismatch (Page 1): The uploaded certificate shows Registration Number '${detectedOther}', but your Roll Number is '${expectedRoll}'. You cannot upload another student's record.`
      };
    }
    return { valid: false, definitiveMismatch: false };
  }

  // 3. Subject Code & Subject Name Check
  const pedCodesFound = (text.toUpperCase().match(/\bP[\s-_]*ED[\s-_]*\d{1,2}[A-Z]?\b/g) || []).map((c) => normalize(c));
  const uniquePedCodes = [...new Set(pedCodesFound)];

  let subCodeMatches = false;
  if (normExpectedSubCode) {
    if (normText.includes(normExpectedSubCode)) {
      subCodeMatches = true;
    } else {
      const codeMatch = normExpectedSubCode.match(/^([A-Z]+)(\d+)([A-Z]*)$/);
      if (codeMatch) {
        const [, prefix, digits, suffix] = codeMatch;
        const flexPrefix = prefix.split('').join('[\\s-_]*');
        const digitRegex = digits
          .replace(/0/g, '[0OQ]')
          .replace(/1/g, '[1IL]')
          .replace(/5/g, '[5S]')
          .replace(/8/g, '[8B]');
        const flexSuffix = suffix ? `[\\s-_]*${suffix}` : '';
        const pattern = new RegExp(`${flexPrefix}[\\s-_]*${digitRegex}${flexSuffix}(?![A-Z0-9])`);
        if (pattern.test(text.toUpperCase())) {
          subCodeMatches = true;
        }
      }
    }
  }

  if (normExpectedSubCode && uniquePedCodes.length > 0 && !subCodeMatches) {
    const conflicting = uniquePedCodes.find((c) => c !== normExpectedSubCode);
    if (conflicting) {
      const displayExpected = expectedGroupName
        ? `${expectedGroupName} (${expectedSubCode})`
        : `${expectedSubCode} - ${expectedSubName}`;
      return {
        valid: false,
        definitiveMismatch: true,
        error: `Subject Mismatch (Page 1): You are uploading for '${displayExpected}', but the Certificate belongs to subject '${conflicting}'. Please select the correct record for this subject.`
      };
    }
  }

  const matchesPhrase = (phrase) => {
    const normPhrase = normalize(phrase);
    if (!normPhrase) return false;
    if (normText.includes(normPhrase)) return true;
    const words = (phrase || '')
      .toUpperCase()
      .split(/[^A-Z0-9]+/)
      .filter((w) => w.length >= 4);
    if (words.length >= 1) {
      const hitCount = words.filter((w) => {
        const stem = w.replace(/S$/, '');
        return normText.includes(w) || (stem.length >= 4 && normText.includes(stem));
      }).length;
      return hitCount >= Math.ceil(words.length * 0.75);
    }
    return false;
  };

  const groupMatches = normExpectedGroup ? matchesPhrase(expectedGroupName) : false;
  const subNameMatches = normExpectedSubName ? matchesPhrase(expectedSubName) : false;

  let subjectMatches;
  if (normExpectedSubCode && normExpectedGroup) {
    // Pedagogy/group records require BOTH exact subject code (e.g. P-ED-27A vs P-ED-28A) and group subject name (e.g. MATHEMATICS vs ENGLISH)
    subjectMatches = subCodeMatches && groupMatches;
  } else if (normExpectedSubCode) {
    subjectMatches = subCodeMatches || (uniquePedCodes.length === 0 && subNameMatches);
  } else {
    subjectMatches = groupMatches || subNameMatches;
  }

  if (!subjectMatches) {
    return { valid: false, definitiveMismatch: false };
  }

  return { valid: true };
}

/**
 * Runs Tesseract OCR on the upper 80% of Certificate Page 1 as a fallback when QR is blurred/unreadable.
 */
async function runPage1Ocr(page1Canvas, page1Ctx) {
  const cropW = page1Canvas.width;
  const cropH = Math.max(20, Math.floor(page1Canvas.height * 0.80));
  const rawImg = page1Ctx.getImageData(0, 0, cropW, cropH);
  const enhanced = createEnhancedImageData(rawImg, { gamma: 0.72, contrastBoost: 1.22 });
  const ocrCanvas = imageDataToCanvas(enhanced);

  let worker = null;
  try {
    const { createWorker } = await import('tesseract.js');
    worker = await createWorker('eng', 1, {
      errorHandler: (err) => console.warn('OCR worker notice:', err)
    });
    const ocrPromise = worker.recognize(ocrCanvas);
    const timeoutPromise = new Promise((_, reject) =>
      setTimeout(() => reject(new Error('OCR verification timed out')), 25000)
    );
    const result = await Promise.race([ocrPromise, timeoutPromise]);
    return result?.data?.text || '';
  } finally {
    releaseCanvas(ocrCanvas);
    if (worker) {
      try {
        await worker.terminate();
      } catch (termErr) {
        console.warn('OCR worker cleanup warning:', termErr);
      }
    }
  }
}

/**
 * Verifies that the uploaded PDF belongs to the student and subject by:
 * 1. Scanning the first 3 pages for the portal QR code (passing on the 1st matching page).
 * 2. Deep-scanning Page 1 (Certificate cover page) at higher resolution if needed.
 * 3. Falling back to Certificate Page 1 embedded text / OCR check if the QR is too blurred/compressed.
 *
 * @param {File} fileObj - Uploaded PDF file object
 * @param {Object} assignment - Assignment being submitted
 * @param {Object} user - Logged in student user object
 * @param {Function} onProgress - Callback with status message
 * @returns {Promise<{ success: boolean, message?: string, qrData?: string, method?: 'qr'|'ocr' }>}
 */
export async function verifyPdfRecordQrCode(fileObj, assignment, user, onProgress) {
  try {
    if (!fileObj) {
      return { success: false, message: 'Please select a PDF file to upload.' };
    }

    const expectedRoll = (user?.regdNo || assignment?.studentId?.regdNo || '').trim().toUpperCase();
    const expectedSubCode = (assignment?.subjectId?.subCode || '').trim().toUpperCase();
    const expectedGroupName = (assignment?.groupSubjectName || '').trim().toUpperCase();
    const expectedSubName = (assignment?.subjectId?.subName || assignment?.groupSubjectName || '').trim();

    const normExpectedRoll = normalize(expectedRoll);
    const normExpectedSubCode = normalize(expectedSubCode);
    const normExpectedGroup = normalize(expectedGroupName);

    if (onProgress) onProgress('Reading PDF document...');

    const arrayBuffer = await fileObj.arrayBuffer();
    let pdf;
    try {
      const loadingTask = pdfjsLib.getDocument({ data: arrayBuffer });
      pdf = await loadingTask.promise;
    } catch (workerErr) {
      console.warn('Initial PDF loading with local worker failed, falling back to CDN worker:', workerErr);
      pdfjsLib.GlobalWorkerOptions.workerSrc = CDN_WORKER_URL;
      const fallbackTask = pdfjsLib.getDocument({ data: arrayBuffer });
      pdf = await fallbackTask.promise;
    }

    if (!pdf.numPages || pdf.numPages < 1) {
      return { success: false, message: 'Invalid or empty PDF document.' };
    }

    const maxPagesToScan = Math.min(3, pdf.numPages);
    let detectedQrCodes = [];

    // Helper validator
    const validateDetectedQr = (qrRaw, pageNum) => {
      const parsed = parseQrPayload(qrRaw);
      const normQR = normalize(qrRaw);
      const normDetectedRoll = normalize(parsed.rollNumber);

      // Check 1: Student Roll Number Check
      let rollMatches = false;
      if (normExpectedRoll) {
        if (normDetectedRoll === normExpectedRoll || normQR.includes(normExpectedRoll)) {
          rollMatches = true;
        }
      } else {
        rollMatches = true;
      }

      if (!rollMatches) {
        return {
          valid: false,
          error: `Student Roll Number Mismatch (Page ${pageNum}): The uploaded record contains QR Code for student '${parsed.rollNumber || qrRaw}', but your Roll Number is '${expectedRoll}'. You cannot upload another student's record.`
        };
      }

      // Check 2: Subject Code Check
      let subjectMatches = false;
      const normDetectedSub = normalize(parsed.subjectPart);

      if (normExpectedSubCode && (normDetectedSub === normExpectedSubCode || normDetectedSub.includes(normExpectedSubCode) || normExpectedSubCode.includes(normDetectedSub))) {
        subjectMatches = true;
      }
      if (normExpectedGroup && (normDetectedSub === normExpectedGroup || normDetectedSub.includes(normExpectedGroup) || normExpectedGroup.includes(normDetectedSub))) {
        subjectMatches = true;
      }
      if (!subjectMatches) {
        if (normExpectedSubCode && normQR.includes(normExpectedSubCode)) subjectMatches = true;
        if (normExpectedGroup && normQR.includes(normExpectedGroup)) subjectMatches = true;
      }

      if (!subjectMatches) {
        const displayDetected = parsed.subjectPart || qrRaw;
        const displayExpected = expectedGroupName ? `${expectedGroupName} (${expectedSubCode})` : (expectedSubCode ? `${expectedSubCode} - ${expectedSubName}` : expectedSubName);
        return {
          valid: false,
          error: `Subject Mismatch (Page ${pageNum}): You are uploading for '${displayExpected}', but the document QR Code belongs to subject '${displayDetected}'. Please select the correct record for this subject.`
        };
      }

      return { valid: true, parsed };
    };

    // Primary Pass: Scan pages 1 to 3 at bounded high-resolution (passes on first valid QR match)
    for (let pageNum = 1; pageNum <= maxPagesToScan; pageNum++) {
      if (onProgress) {
        onProgress(`Scanning Page ${pageNum} of ${maxPagesToScan} for QR Code...`);
      }

      const page = await pdf.getPage(pageNum);
      let canvas = null;
      try {
        const rendered = await renderPageToCanvas(page, { targetMaxDim: 1850, minScale: 0.6, maxScale: 2.5 });
        canvas = rendered.canvas;
        const qrRaw = await findQrOnCanvas(canvas, rendered.context);

        if (qrRaw) {
          const check = validateDetectedQr(qrRaw, pageNum);
          if (!check.valid) {
            return { success: false, message: check.error };
          }

          detectedQrCodes.push({ pageNum, parsed: check.parsed, qrRaw });
          break;
        }
      } finally {
        releaseCanvas(canvas);
        if (typeof page.cleanup === 'function') page.cleanup();
      }
    }

    // Secondary Pass: If not detected yet, perform a higher-DPI scan on Page 1
    if (detectedQrCodes.length === 0 && pdf.numPages >= 1) {
      if (onProgress) {
        onProgress('Performing deep scan with brightness enhancement on Certificate page...');
      }

      let page1 = null;
      let canvas = null;
      try {
        page1 = await pdf.getPage(1);
        const rendered = await renderPageToCanvas(page1, { targetMaxDim: 2600, minScale: 0.85, maxScale: 3.2 });
        canvas = rendered.canvas;
        const qrRaw = await findQrOnCanvas(canvas, rendered.context);

        if (qrRaw) {
          const check = validateDetectedQr(qrRaw, 1);
          if (!check.valid) {
            return { success: false, message: check.error };
          }
          detectedQrCodes.push({ pageNum: 1, parsed: check.parsed, qrRaw });
        }
      } catch (deepErr) {
        console.warn('Deep scan attempt encountered an issue:', deepErr);
      } finally {
        releaseCanvas(canvas);
        if (page1 && typeof page1.cleanup === 'function') page1.cleanup();
      }
    }

    // Tertiary Fallback: If QR was blurred/damaged by heavy compression, verify Certificate Page 1 text / OCR
    if (detectedQrCodes.length === 0 && pdf.numPages >= 1) {
      let page1 = null;
      let ocrCanvas = null;
      try {
        page1 = await pdf.getPage(1);

        // Step 3A: Fast check of embedded PDF text layer (e.g., iOS / Adobe Scan Live Text)
        try {
          const textContent = await page1.getTextContent();
          const embeddedText = (textContent?.items || []).map((item) => item.str || '').join(' ');
          if (embeddedText.trim().length >= 20) {
            const textCheck = validateCertificateText(embeddedText, {
              expectedRoll,
              expectedSubCode,
              expectedGroupName,
              expectedSubName
            });
            if (textCheck.definitiveMismatch) {
              return { success: false, message: textCheck.error };
            }
            if (textCheck.valid) {
              const verifiedTag = `OCR_VERIFIED-${expectedRoll || 'STUDENT'}-${expectedSubCode || expectedGroupName || 'SUB'}`;
              if (onProgress) onProgress('Certificate details verified!');
              return {
                success: true,
                qrData: verifiedTag,
                pagesVerified: 1,
                method: 'ocr'
              };
            }
          }
        } catch (textErr) {
          console.warn('PDF text layer check skipped:', textErr);
        }

        // Step 3B: Tesseract OCR on Certificate Page 1
        if (onProgress) {
          onProgress('QR unclear — verifying Certificate Page 1 text...');
        }

        const rendered = await renderPageToCanvas(page1, { targetMaxDim: 2000, minScale: 0.7, maxScale: 2.6 });
        ocrCanvas = rendered.canvas;
        const ocrText = await runPage1Ocr(ocrCanvas, rendered.context);

        const ocrCheck = validateCertificateText(ocrText, {
          expectedRoll,
          expectedSubCode,
          expectedGroupName,
          expectedSubName
        });

        if (ocrCheck.definitiveMismatch) {
          return { success: false, message: ocrCheck.error };
        }
        if (ocrCheck.valid) {
          const verifiedTag = `OCR_VERIFIED-${expectedRoll || 'STUDENT'}-${expectedSubCode || expectedGroupName || 'SUB'}`;
          if (onProgress) onProgress('Certificate details verified!');
          return {
            success: true,
            qrData: verifiedTag,
            pagesVerified: 1,
            method: 'ocr'
          };
        }
      } catch (ocrErr) {
        console.warn('OCR fallback encountered an issue:', ocrErr);
      } finally {
        releaseCanvas(ocrCanvas);
        if (page1 && typeof page1.cleanup === 'function') page1.cleanup();
      }
    }

    // Verify that at least one QR code or Certificate Page 1 verification succeeded
    if (detectedQrCodes.length === 0) {
      return {
        success: false,
        message: `Could not verify QR Code or Certificate details in the first ${maxPagesToScan} pages.\n\n` +
          `Possible causes & solutions:\n` +
          `1. Missing Cover Page: Ensure the official Certificate / Barcode cover page generated from this portal is Page 1.\n` +
          `2. Wrong Subject or Roll Number: Check that you selected the matching subject and your Registration Number is clearly visible on Page 1.\n` +
          `3. Dark or Blurry Scan: Re-scan Page 1 in good light using 'Document / B&W' mode and avoid extreme PDF compression.`
      };
    }

    if (onProgress) onProgress('QR Code verified successfully!');

    return {
      success: true,
      qrData: detectedQrCodes[0].qrRaw,
      pagesVerified: detectedQrCodes.length,
      method: 'qr'
    };
  } catch (err) {
    console.error('PDF QR Verification Error:', err);
    return {
      success: false,
      message: `Failed to verify PDF document: ${err.message || 'Corrupted or unreadable PDF file. Please ensure it is a valid PDF.'}`
    };
  }
}
